export type IconName = keyof typeof ICONS;

const WEIGHT: Partial<Record<IconName, IconWeight>> = {
  send: "bold",
  stop: "fill",
  chevron: "bold",
  "pin-solid": "fill",
};

export function Icon({ name, size = 18 }: { name: IconName; size?: number }) {
  const Glyph = ICONS[name];
  return <Glyph className="icon" size={size} weight={WEIGHT[name] ?? "regular"} aria-hidden="true" />;
}
